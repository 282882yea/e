local function base64Decode(data)
	local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	local lut = table.create(256, 0)
	for i = 1, 64 do
		lut[string.byte(alphabet, i) + 1] = i - 1
	end
	local len = #data
	local pad = 0
	if string.sub(data, -2) == "==" then
		pad = 2
	elseif string.sub(data, -1) == "=" then
		pad = 1
	end
	local outLen = math.floor(len / 4) * 3 - pad
	if buffer then
		local src = buffer.fromstring(data)
		local out = buffer.create(outLen)
		local o = 0
		for i = 0, len - 4, 4 do
			local n = lut[buffer.readu8(src, i) + 1] * 262144
				+ lut[buffer.readu8(src, i + 1) + 1] * 4096
				+ lut[buffer.readu8(src, i + 2) + 1] * 64
				+ lut[buffer.readu8(src, i + 3) + 1]
			if o < outLen then
				buffer.writeu8(out, o, bit32.band(bit32.rshift(n, 16), 255))
			end
			if o + 1 < outLen then
				buffer.writeu8(out, o + 1, bit32.band(bit32.rshift(n, 8), 255))
			end
			if o + 2 < outLen then
				buffer.writeu8(out, o + 2, bit32.band(n, 255))
			end
			o += 3
		end
		return buffer.tostring(out)
	end
	local parts, chunk, o = {}, {}, 0
	for i = 1, len - 3, 4 do
		local a, b, c, d = string.byte(data, i, i + 3)
		local n = lut[a + 1] * 262144 + lut[b + 1] * 4096 + lut[c + 1] * 64 + lut[d + 1]
		for shift = 16, 0, -8 do
			if o < outLen then
				chunk[#chunk + 1] = string.char(bit32.band(bit32.rshift(n, shift), 255))
				o += 1
			end
		end
		if #chunk >= 3000 then
			parts[#parts + 1] = table.concat(chunk)
			chunk = {}
		end
	end
	parts[#parts + 1] = table.concat(chunk)
	return table.concat(parts)
end

local function ensureFolder(path)
	if type(makefolder) ~= "function" then
		return false
	end
	local current = ""
	for part in string.gmatch(path, "[^/]+") do
		current = current == "" and part or (current .. "/" .. part)
		local exists = type(isfolder) == "function" and isfolder(current)
		if not exists then
			pcall(makefolder, current)
		end
	end
	return true
end

local ASSET_NAMES = { "background", "blossoms", "flowers_left", "flowers_right", "petal", "glow", "icons", "logo" }

local function loadAssets(folder)
	local getasset = getcustomasset or getsynasset
	local canWrite = type(writefile) == "function" and type(getasset) == "function"
	local files = EMBEDDED.files or {}
	local dir = folder .. "/assets/lunar-" .. tostring(EMBEDDED.version or "dev")
	if canWrite then
		ensureFolder(dir)
	end
	for _, name in ipairs(ASSET_NAMES) do
		local id
		if canWrite and files[name] then
			local ok, result = pcall(function()
				local path = dir .. "/" .. name .. ".png"
				local exists = type(isfile) == "function" and isfile(path)
				if not exists then
					writefile(path, base64Decode(files[name]))
				end
				return getasset(path)
			end)
			if ok and type(result) == "string" then
				id = result
			end
		end
		Assets[name] = id or ""
	end
end

