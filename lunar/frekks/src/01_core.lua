local function setIcon(image, name)
	if type(name) ~= "string" or name == "" then
		image.Image = ""
		return false
	end
	if string.find(name, "^rbx") or string.find(name, "^http") then
		image.Image = name
		image.ImageRectOffset = Vector2.new(0, 0)
		image.ImageRectSize = Vector2.new(0, 0)
		return true
	end
	local cell = ICONS[name] or ICONS[ICON_ALIASES[string.lower(name)] or ""]
	if cell and Assets.icons ~= "" then
		image.Image = Assets.icons
		image.ImageRectOffset = Vector2.new(cell[1], cell[2])
		image.ImageRectSize = Vector2.new(ICON_CELL, ICON_CELL)
		return true
	end
	image.Image = ""
	return false
end

