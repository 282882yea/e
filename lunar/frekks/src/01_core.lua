local function colorSeq(...)
	local points = { ... }
	if #points == 2 and typeof(points[1]) == "Color3" then
		return ColorSequence.new(points[1], points[2])
	end
	local keys = {}
	for i = 1, #points, 2 do
		table.insert(keys, ColorSequenceKeypoint.new(points[i], points[i + 1]))
	end
	return ColorSequence.new(keys)
end

local function numberSeq(...)
	local points = { ... }
	local keys = {}
	for i = 1, #points, 2 do
		table.insert(keys, NumberSequenceKeypoint.new(points[i], points[i + 1]))
	end
	return NumberSequence.new(keys)
end

-- gradient(parent, rotation, keys, transparency): keys is a list of {time, "ThemeKey"} or two theme keys
local function gradient(parent, rotation, keys, transparency)
	local g = makeInstance("UIGradient")
	g.Rotation = rotation or 0
	if keys then
		local function build(target)
			if #keys == 2 and type(keys[1]) == "string" then
				target.Color = ColorSequence.new(Theme[keys[1]], Theme[keys[2]])
			else
				local points = {}
				for _, k in ipairs(keys) do
					table.insert(points, ColorSequenceKeypoint.new(k[1], Theme[k[2]]))
				end
				target.Color = ColorSequence.new(points)
			end
		end
		build(g)
		paintedGradients[g] = build
	end
	if transparency then
		g.Transparency = transparency
	end
	g.Parent = parent
	return g
end

