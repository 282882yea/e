local function deriveColor(color, fromBase, toBase)
	if fromBase == toBase then
		return color
	end
	local h, s, v = color:ToHSV()
	local h0, s0, v0 = fromBase:ToHSV()
	local h1, s1, v1 = toBase:ToHSV()
	local nh = (h + (h1 - h0)) % 1
	local ns = s0 > 0.02 and math.clamp(s * s1 / s0, 0, 1) or s1
	local nv = v0 > 0.02 and math.clamp(v * v1 / v0, 0, 1) or math.clamp(v1 + (v - v0), 0, 1)
	return Color3.fromHSV(nh, ns, nv)
end

-- Instances whose colours follow the theme: painted[instance] = { Property = "ThemeKey" }
local painted = setmetatable({}, { __mode = "k" })
local paintedGradients = setmetatable({}, { __mode = "k" })
local themeHooks = {}

local function paint(instance, map)
	local entry = painted[instance]
	if not entry then
		entry = {}
		painted[instance] = entry
	end
	for prop, key in pairs(map) do
		entry[prop] = key
		instance[prop] = Theme[key]
	end
	return instance
end

local function onTheme(fn)
	table.insert(themeHooks, fn)
	fn()
end

local function applyTheme()
	for instance, map in pairs(painted) do
		for prop, key in pairs(map) do
			pcall(function()
				instance[prop] = Theme[key]
			end)
		end
	end
	for gradient, build in pairs(paintedGradients) do
		pcall(build, gradient)
	end
	for _, fn in ipairs(themeHooks) do
		pcall(fn)
	end
end

local function setScheme(scheme)
	for key, def in pairs(PALETTE) do
		Theme[key] = deriveColor(def[1], BASE[def[2]], scheme[def[2]] or BASE[def[2]])
	end
	applyTheme()
end

