local function keyLabel(value)
	local name = enumToString(value)
	return KEY_LABELS[name] or (string.gsub(name, "(%l)(%u)", "%1 %2"))
end

local function inputMatches(input, value)
	if typeof(value) ~= "EnumItem" or value == KEY_NONE then
		return false
	end
	if value.EnumType == Enum.KeyCode then
		return input.UserInputType == Enum.UserInputType.Keyboard and input.KeyCode == value
	end
	return input.UserInputType == value
end

