end

---------------------------------------------------------------------
-- Glow: UIShadow where the client has it, 9-slice halo otherwise.
-- Every glow scales with Library.GlowStrength (the "Glow strength" slider).
---------------------------------------------------------------------

local SHADOW_OK = pcall(function()
	makeInstance("UIShadow"):Destroy()
end)

local glows = setmetatable({}, { __mode = "k" })

local function glowFactor()
	return math.clamp((tonumber(Library.GlowStrength) or 0.2) / 0.2, 0, 2.5)
end

local function effective(base, colorIsBlack)
	if colorIsBlack then
		return base -- drop shadows keep their depth
	end
	return math.clamp(1 - (1 - base) * glowFactor(), 0, 1)
end

local function glow(parent, opts)
	local handle = { Base = opts.Transparency or 0.5, Black = opts.Color == "Black" }
	if SHADOW_OK then
		local shadow = makeInstance("UIShadow")
		shadow.Name = "Glow"
		if handle.Black then
			shadow.Color = BLACK
		else
			paint(shadow, { Color = opts.Color or "Glow" })
		end
		shadow.BlurRadius = px(opts.Blur or 12)
		local offset = opts.Offset or Vector2.new(0, 0)
		trySet(shadow, "Spread", UDim2.fromOffset(opts.Spread or 0, opts.Spread or 0))
		trySet(shadow, "Offset", UDim2.fromOffset(offset.X, offset.Y))
		trySet(shadow, "ShowBehindParent", false)
		pcall(function()
			shadow.Mode = Enum.ApplyShadowMode.Shape
		end)
		shadow.Transparency = effective(handle.Base, handle.Black)
		shadow.Parent = parent
		handle.Instance, handle.Property = shadow, "Transparency"
	elseif Assets.glow ~= "" then
		local scale = math.max(0.2, (opts.Blur or 12) / 20)
		local margin = 32 * scale + (opts.Spread or 0)
		local offset = opts.Offset or Vector2.new(0, 0)
		local halo = new("ImageLabel", {
			Name = "Glow",
			AnchorPoint = Vector2.new(0.5, 0.5),
			Position = UDim2.new(0.5, offset.X, 0.5, offset.Y),
			Size = UDim2.new(1, margin * 2, 1, margin * 2),
			Image = Assets.glow,
			ImageTransparency = effective(handle.Base, handle.Black),
			ScaleType = Enum.ScaleType.Slice,
			SliceCenter = Rect.new(47, 47, 49, 49),
			SliceScale = scale,
			ZIndex = 0,
			Parent = parent,
		})
		if handle.Black then
			halo.ImageColor3 = BLACK
		else
			paint(halo, { ImageColor3 = opts.Color or "Glow" })
		end
		handle.Instance, handle.Property = halo, "ImageTransparency"
	end
	if handle.Instance then
		glows[handle] = true
	end
	return handle
end

local function setGlow(handle, base, time)
	if not handle then
		return
	end
	handle.Base = base
	if not handle.Instance then
		return
	end
	local value = effective(base, handle.Black)
	if time and time > 0 then
		tween(handle.Instance, time, { [handle.Property] = value })
	else
		handle.Instance[handle.Property] = value
	end
end

local function refreshGlows()
	for handle in pairs(glows) do
		if handle.Instance and handle.Instance.Parent then
			handle.Instance[handle.Property] = effective(handle.Base, handle.Black)
		end
	end
end

---------------------------------------------------------------------
-- Fade: tween the visible part of a subtree to transparent and back.
-- Hidden subtrees (inactive pages) are skipped to keep the tween count low.
---------------------------------------------------------------------

local FADE_PROPS = {
	Frame = { "BackgroundTransparency" },
	ScrollingFrame = { "BackgroundTransparency", "ScrollBarImageTransparency" },
	TextLabel = { "BackgroundTransparency", "TextTransparency" },
	TextButton = { "BackgroundTransparency", "TextTransparency" },
	TextBox = { "BackgroundTransparency", "TextTransparency" },
	ImageLabel = { "BackgroundTransparency", "ImageTransparency" },
	ImageButton = { "BackgroundTransparency", "ImageTransparency" },
	ViewportFrame = { "BackgroundTransparency", "ImageTransparency" },
	UIStroke = { "Transparency" },
	UIShadow = { "Transparency" },
}

local fades = setmetatable({}, { __mode = "k" })

local function fadeFinish(root)
	local state = fades[root]
	if not state then
		return
	end
	fades[root] = nil
	for _, t in ipairs(state.tweens) do
		t:Cancel()
	end
	for _, item in ipairs(state.items) do
		pcall(function()
			item[1][item[2]] = item[3]
		end)
	end
end

local function fade(root, show, time, onDone)
	fadeFinish(root)
	local items = {}
	local function collect(inst)
		local props = FADE_PROPS[inst.ClassName]
		if props then
			for _, prop in ipairs(props) do
				local value = inst[prop]
				if value < 1 then
					table.insert(items, { inst, prop, value })
				end
			end
		end
		if inst:IsA("GuiObject") and not inst.Visible and inst ~= root then
			return
		end
		for _, child in ipairs(inst:GetChildren()) do
			collect(child)
		end
	end
	collect(root)

	local state = { items = items, tweens = {} }
	fades[root] = state
	local info = TweenInfo.new(time, Enum.EasingStyle.Quad, OUT)
	if show then
		for _, item in ipairs(items) do
			item[1][item[2]] = 1
		end
		root.Visible = true
	end
	for _, item in ipairs(items) do
		local t = TweenService:Create(item[1], info, { [item[2]] = show and item[3] or 1 })
		table.insert(state.tweens, t)
		t:Play()
	end
	task.delay(time, function()
		if fades[root] ~= state then
			return
		end
		if not show then
			root.Visible = false
		end
		fadeFinish(root)
		if onDone then
			onDone()
		end
	end)
end

---------------------------------------------------------------------
-- Backdrop blur: UIBlur when the client has it, otherwise a glass part
-- with a DepthOfFieldEffect placed just in front of the camera.
---------------------------------------------------------------------

local function createGlassBlur(target)
	local folder = makeInstance("Folder")
	folder.Name = HttpService:GenerateGUID(false)
	local part = makeInstance("Part")
	part.Name = "Glass"
	part.Material = Enum.Material.Glass
	part.Color = BLACK
	part.Transparency = 0.98
	part.Anchored = true
	part.CanCollide = false
	part.CastShadow = false
	part.Locked = true
	part.Size = Vector3.new(1, 1, 0)
	trySet(part, "CanQuery", false)
	trySet(part, "CanTouch", false)
	local mesh = makeInstance("SpecialMesh")
	mesh.MeshType = Enum.MeshType.Brick
	mesh.Offset = Vector3.new(0, 0, -0.000001)
	mesh.Parent = part
	part.Parent = folder
	local dof = makeInstance("DepthOfFieldEffect")
	dof.Name = folder.Name
	dof.FarIntensity = 0
	dof.FocusDistance = 0.05
	dof.InFocusRadius = 0.1
	dof.NearIntensity = 1

	local enabled = false
	local function update()
		local camera = workspace.CurrentCamera
		if not enabled or not camera then
			return
		end
		if folder.Parent ~= camera then
			folder.Parent = camera
		end
		local pos, size = target.AbsolutePosition, target.AbsoluteSize
		local inset = 8 + 48 * math.clamp(camera.ViewportSize.Y / 2560, 0, 1)
		local x0, y0 = pos.X + inset / 2, pos.Y + inset / 2
		local x1, y1 = pos.X + size.X - inset / 2, pos.Y + size.Y - inset / 2
		if x1 <= x0 or y1 <= y0 then
			return
		end
		local function world(x, y)
			local ray = camera:ViewportPointToRay(x, y)
			return ray.Origin + ray.Direction * 0.001
		end
		local topLeft, topRight, bottomRight = world(x0, y0), world(x1, y0), world(x1, y1)
		local cf = camera.CFrame
		part.CFrame = CFrame.fromMatrix((topLeft + bottomRight) / 2, cf.XVector, cf.YVector, cf.ZVector)
		mesh.Scale = Vector3.new((topRight - topLeft).Magnitude, (topRight - bottomRight).Magnitude, 0)
	end
	local conn = connect(RunService.RenderStepped, update)
	return {
		SetEnabled = function(_, on)
			enabled = on
			folder.Parent = on and workspace.CurrentCamera or nil
			dof.Parent = on and Lighting or nil
			if on then
				update()
			end
		end,
		Destroy = function()
			conn:Disconnect()
			folder:Destroy()
			dof:Destroy()
		end,
	}
end

local function createBlur(mode, target, strength)
	if mode == false or mode == "None" then
		return nil
	end
	local wantGlass = mode == "Glass" or mode == "Both"
	local uiBlur, glass
	if mode ~= "Glass" then
		local ok, inst = pcall(Instance.new, "UIBlur")
		if ok and inst then
			pcall(function()
				inst.Strength = Enum.UIBlurStrength[strength or "Medium"]
			end)
			inst.Parent = target
			uiBlur = inst
		elseif mode ~= "UIBlur" then
			wantGlass = true
		end
	end
	if wantGlass then
		local ok, handle = pcall(createGlassBlur, target)
		glass = ok and handle or nil
	end
	if not uiBlur and not glass then
		return nil
	end
	return {
		Kind = uiBlur and (glass and "Both" or "UIBlur") or "Glass",
		Instance = uiBlur,
		SetEnabled = function(_, on)
			if uiBlur then
				uiBlur.Enabled = on
			end
			if glass then
				glass:SetEnabled(on)
			end
		end,
		Destroy = function()
			if uiBlur then
				uiBlur:Destroy()
			end
			if glass then
				glass:Destroy()
			end
		end,
	}
end
