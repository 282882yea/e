	LeftShift = "Left Shift", RightShift = "Right Shift", LeftControl = "Left Ctrl", RightControl = "Right Ctrl",
	LeftAlt = "Left Alt", RightAlt = "Right Alt", CapsLock = "Caps Lock", Return = "Enter",
