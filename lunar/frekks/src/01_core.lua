-- Runs a user callback through Library:SafeCallback (the script installs an
-- error-reporting version) on its own thread, like the previous library did.
local function fire(fn, ...)
	if type(fn) ~= "function" then
		return
	end
	local args = table.pack(...)
	task.spawn(function()
		elevate()
		local safe = Library.SafeCallback
		if type(safe) == "function" then
			safe(Library, fn, table.unpack(args, 1, args.n))
		else
			local ok, err = pcall(fn, table.unpack(args, 1, args.n))
			if not ok then
				warn("[Lunar] callback error: " .. tostring(err))
			end
		end
	end)
end

