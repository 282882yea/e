local KEY_NONE = Enum.KeyCode.Unknown

local function enumToString(value)
	if typeof(value) ~= "EnumItem" then
		return tostring(value)
	end
	if value == KEY_NONE then
		return "None"
	end
	if value.EnumType == Enum.UserInputType then
		if value == Enum.UserInputType.MouseButton1 then
			return "MB1"
		elseif value == Enum.UserInputType.MouseButton2 then
			return "MB2"
		elseif value == Enum.UserInputType.MouseButton3 then
			return "MB3"
		end
	end
	return value.Name
end

local KEY_ALIASES = {
	MB1 = Enum.UserInputType.MouseButton1,
	MB2 = Enum.UserInputType.MouseButton2,
	MB3 = Enum.UserInputType.MouseButton3,
	MouseButton1 = Enum.UserInputType.MouseButton1,
	MouseButton2 = Enum.UserInputType.MouseButton2,
	MouseButton3 = Enum.UserInputType.MouseButton3,
	None = KEY_NONE,
	Unknown = KEY_NONE,
}

local function stringToEnum(value)
	if typeof(value) == "EnumItem" then
		return value
	end
	local text = tostring(value or "")
	if KEY_ALIASES[text] then
		return KEY_ALIASES[text]
	end
	local ok, item = pcall(function()
		return Enum.KeyCode[text]
	end)
	if ok and item then
		return item
	end
	ok, item = pcall(function()
		return Enum.UserInputType[text]
	end)
	if ok and item then
		return item
	end
	return KEY_NONE
end

