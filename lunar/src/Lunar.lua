		BackgroundColor3 = WHITE,
		BackgroundTransparency = 0,
		Parent = track,
	})
	corner(fill, 9)
	gradient(fill, 0, colorSeq(Theme.AccentDeep, rgb(240, 136, 182)))

	local knob = new("Frame", {
		Name = "Knob",
		AnchorPoint = Vector2.new(0.5, 0.5),
