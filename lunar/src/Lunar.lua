local Popup = {}
Popup.__index = Popup

-- items: { { Text, Selected?, Icon?, Callback } }
function Popup.open(window, anchor, items, opts)
	if window._popupAnchor == anchor and os.clock() - (window._popupClosed or 0) < 0.2 then
		return nil -- the same press that dismissed it must not reopen it
	end
	window:_closePopup()
	opts = opts or {}

	local scale = window._scale
	local overlay = window._overlay
	local anchorPos = (anchor.AbsolutePosition - overlay.AbsolutePosition) / scale
	local anchorSize = anchor.AbsoluteSize / scale
	local overlaySize = overlay.AbsoluteSize / scale

	local ITEM = 28
	local count = math.min(#items, opts.MaxVisible or 7)
	local height = count * ITEM + 8
	local width = math.max(opts.Width or 0, anchorSize.X, 132)

	local x = anchorPos.X + anchorSize.X - width
	local y = anchorPos.Y + anchorSize.Y + 5
	local below = true
	if y + height > overlaySize.Y - 6 then
		y = anchorPos.Y - height - 5
		below = false
	end
	x = math.clamp(x, 6, math.max(6, overlaySize.X - width - 6))
	y = math.max(6, y)

	local self = setmetatable({ Window = window, Anchor = anchor, OnClose = opts.OnClose }, Popup)

	local catcher = new("TextButton", {
		Name = "PopupCatcher",
		Size = UDim2.fromScale(1, 1),
		ZIndex = 1,
		Parent = overlay,
	})
	catcher.MouseButton1Down:Connect(function()
		window:_closePopup()
	end)
	self.Catcher = catcher

	local frame = new("Frame", {
		Name = "Popup",
		Position = UDim2.fromOffset(round(x), round(y + (below and -6 or 6))),
		Size = UDim2.fromOffset(round(width), height),
		BackgroundColor3 = Theme.Popup,
		BackgroundTransparency = 0,
		ZIndex = 2,
		Parent = overlay,
	})
	corner(frame, 10)
	local border = stroke(frame, WHITE, 1, 0)
	gradient(border, 90, colorSeq(Theme.CardStrokeTop, Theme.CardStrokeMid))
	glow(frame, { Color = BLACK, Blur = 22, Transparency = 0.45, Offset = Vector2.new(0, 8) })
	glow(frame, { Color = Theme.Glow, Blur = 18, Transparency = 0.8 })
	self.Frame = frame

	local list = new("ScrollingFrame", {
		Name = "Items",
		Position = UDim2.fromOffset(4, 4),
		Size = UDim2.new(1, -8, 1, -8),
		BackgroundTransparency = 1,
		CanvasSize = UDim2.fromOffset(0, #items * ITEM),
		ScrollBarThickness = #items > count and 2 or 0,
		ScrollBarImageColor3 = Theme.AccentDeep,
		ScrollingDirection = Enum.ScrollingDirection.Y,
		Parent = frame,
	})
	new("UIListLayout", { SortOrder = Enum.SortOrder.LayoutOrder, Parent = list })

	self.Rows = {}
	for index, item in ipairs(items) do
		local row = new("TextButton", {
			Name = "Item",
			LayoutOrder = index,
			Size = UDim2.new(1, 0, 0, ITEM),
			BackgroundColor3 = WHITE,
			BackgroundTransparency = 1,
			Parent = list,
		})
		corner(row, 7)
		local left = 9
		if item.Icon then
			icon(item.Icon, 14, Theme.TextTitle, {
				AnchorPoint = Vector2.new(0, 0.5),
				Position = UDim2.new(0, 8, 0.5, 0),
				Parent = row,
			})
			left = 29
		end
		local label = new("TextLabel", {
			Name = "Text",
			Position = UDim2.fromOffset(left, 0),
			Size = UDim2.new(1, -left - 26, 1, 0),
			FontFace = Fonts.Label,
			TextSize = 15,
			TextColor3 = item.Selected and Theme.Accent or Theme.Text,
			TextXAlignment = Enum.TextXAlignment.Left,
			TextTruncate = Enum.TextTruncate.AtEnd,
			Text = item.Text,
			Parent = row,
		})
		local check = icon("check", 13, Theme.Accent, {
			Name = "Check",
			AnchorPoint = Vector2.new(1, 0.5),
			Position = UDim2.new(1, -8, 0.5, 0),
			Visible = item.Selected == true,
			Parent = row,
		})
		row.MouseEnter:Connect(function()
			tween(row, 0.12, { BackgroundTransparency = 0.93 })
		end)
		row.MouseLeave:Connect(function()
			tween(row, 0.2, { BackgroundTransparency = 1 })
		end)
		row.MouseButton1Click:Connect(function()
			local keepOpen = item.Callback and item.Callback(self, index) == true
			if not keepOpen then
				window:_closePopup()
			end
		end)
		self.Rows[index] = { Row = row, Label = label, Check = check }
	end

	window._popup = self
	frame.Visible = false
	fade(frame, true, 0.16)
	tween(frame, 0.22, { Position = UDim2.fromOffset(round(x), round(y)) })
	return self
end

function Popup:SetSelected(index, selected)
	local row = self.Rows[index]
	if row then
		row.Check.Visible = selected
		row.Label.TextColor3 = selected and Theme.Accent or Theme.Text
	end
end

function Popup:Close()
	if self.Closed then
		return
	end
	self.Closed = true
	self.Window._popupAnchor = self.Anchor
	self.Window._popupClosed = os.clock()
	self.Catcher:Destroy()
	local frame = self.Frame
	fade(frame, false, 0.12, function()
		frame:Destroy()
	end)
	if self.OnClose then
		self.OnClose()
	end
end

