	do
		local s = tostring(step)
		local dot = string.find(s, ".", 1, true)
		if dot then
			decimals = #s - dot
		end
	end
	local function format(value)
		return string.format("%." .. decimals .. "f", value) .. suffix
	end

	local function layout(animated)
		local width = track.AbsoluteSize.X / self.Window._scale
		if width <= 0 then
			return
		end
		local frac = (max > min) and (self.Value - min) / (max - min) or 0
		local center = math.clamp(frac * width, 9, math.max(9, width - 9))
		local knobPos = UDim2.new(0, center, 0.5, 0)
		local fillSize = UDim2.new(0, center, 1, 0)
		if animated then
			tween(knob, 0.12, { Position = knobPos }, Enum.EasingStyle.Quad)
			tween(fill, 0.12, { Size = fillSize }, Enum.EasingStyle.Quad)
		else
