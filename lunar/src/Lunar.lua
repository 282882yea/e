-- Card fill: header tone down to the divider, then the darker body with a pink floor.
function Module:_paint()
	local scale = self.Window._scale
	local height = self._card.AbsoluteSize.Y / scale
	local headerHeight = self._header.AbsoluteSize.Y / scale
	if height <= 0 or headerHeight <= 0 then
		return
	end
	local t = headerHeight / height
	if t >= 0.95 then
		self._fill.Color = colorSeq(Theme.HeaderTop, Theme.HeaderBottom)
		self._fill.Transparency = numberSeq(0, 0.2, 1, 0.26)
		return
	end
	self._fill.Color = colorSeq(
		0, Theme.HeaderTop,
		t, Theme.HeaderBottom,
		t + 0.002, Theme.BodyTop,
		t + (1 - t) * 0.45, Theme.BodyMid,
		1, Theme.BodyLow
	)
	self._fill.Transparency = numberSeq(0, 0.16, t, 0.24, t + 0.002, 0.16, 1, 0.2)
end

function Module:_height()
	local scale = self.Window._scale
	local source = self.Collapsed and self._header or self._content
	return math.max(1, round(source.AbsoluteSize.Y / scale))
end

function Module:_place(column, y, height, animated)
	local position = UDim2.new(column * 0.5, column * CARD_GAP_X / 2, 0, y)
	local size = UDim2.new(0.5, -CARD_GAP_X / 2, 0, height)
	if animated and self._placed then
		tween(self._card, 0.32, { Position = position, Size = size })
	else
		self._card.Position = position
		self._card.Size = size
	end
	self._placed = true
end

