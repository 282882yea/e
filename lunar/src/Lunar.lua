		ZIndex = 2,
		Parent = track,
	})
	corner(knob, 7)
	local halo = glow(knob, { Color = Theme.Glow, Blur = 9, Transparency = 0.5 })

	new("Frame", { Name = "Gap", LayoutOrder = 4, Size = UDim2.fromOffset(8, 1), BackgroundTransparency = 1, Parent = line })

