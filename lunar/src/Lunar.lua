		value = tonumber(string.format("%." .. decimals .. "f", value))
		local changed = value ~= self.Value
		self.Value = value
		input.Text = format(value)
		layout(self._ready)
		if self.Flag then
			Lunar.Flags[self.Flag] = value
		end
		if changed and not silent then
			self:_fire()
		end
