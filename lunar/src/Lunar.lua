	end)
	input.FocusLost:Connect(function()
		tween(boxBorder, 0.25, { Color = Theme.ControlStroke })
		local typed = tonumber((string.gsub(input.Text, "[^%d%.%-]", "")))
		if typed then
			self:Set(typed)
		else
			input.Text = format(self.Value)
		end
	end)

	self.Value = nil
	self:Set(cfg.Default or min, true)
	self.Default = self.Value
	self._ready = true
	return self
end

-- Dropdown ----------------------------------------------------------

local function addDropdown(module, cfg)
	local self, row = baseControl(module, "Dropdown", cfg, 43)
	rowLabel(row, self.Name)
	self.Options = cfg.Options or cfg.Values or {}
	self.Multi = cfg.Multi == true

	local open = false
	local toggleOpen
	local pill, valueLabel, chevron = selectPill(row, "", function()
		toggleOpen()
	end)

	local function display()
		if self.Multi then
			local picked = {}
			for _, option in ipairs(self.Options) do
				if self.Value[option] then
					table.insert(picked, tostring(option))
				end
			end
			return #picked > 0 and table.concat(picked, ", ") or "None"
		end
		return self.Value ~= nil and tostring(self.Value) or "None"
	end

	function self:Set(value, silent)
		if self.Multi then
			local set = {}
			if type(value) == "table" then
				for key, v in pairs(value) do
					if type(key) == "number" then
						set[v] = true
					elseif v then
						set[key] = true
					end
				end
			end
			self.Value = set
		else
			if value == self.Value and self._ready then
				return
			end
			self.Value = value
		end
		valueLabel.Text = display()
		if self.Flag then
			Lunar.Flags[self.Flag] = self.Value
		end
		if not silent then
			self:_fire()
		end
	end

	function self:Refresh(options, keep)
		self.Options = options
		if not keep then
			self:Set(self.Multi and {} or options[1], true)
		end
	end

	toggleOpen = function()
		if open then
			self.Window:_closePopup()
			return
		end
		local items = {}
		for _, option in ipairs(self.Options) do
			local selected
			if self.Multi then
				selected = self.Value[option] == true
			else
				selected = self.Value == option
			end
			table.insert(items, {
				Text = tostring(option),
				Selected = selected,
				Callback = function(popup, index)
					if self.Multi then
						local set = table.clone(self.Value)
						set[option] = not set[option] or nil
						self:Set(set)
						popup:SetSelected(index, set[option] == true)
						return true
					end
					self:Set(option)
				end,
			})
		end
		local popup = Popup.open(self.Window, pill, items, {
			OnClose = function()
				open = false
				tween(chevron, 0.25, { Rotation = 0 })
			end,
		})
		if popup then
			open = true
			tween(chevron, 0.25, { Rotation = 180 })
		end
	end

	local default = cfg.Default
	if default == nil and not self.Multi then
		default = self.Options[1]
	end
	self:Set(default, true)
	self.Default = self.Multi and table.clone(self.Value) or self.Value
	self._ready = true
	return self
end

-- Keybind -----------------------------------------------------------

local function addKeybind(module, cfg)
	local self, row = baseControl(module, "Keybind", cfg, 43)
	rowLabel(row, self.Name)
	local listening = false
	local beginCapture
	local pill, valueLabel, chevron, border = selectPill(row, "", function()
		beginCapture()
	end)
	self.Pressed = cfg.Pressed or cfg.OnPressed

	function self:Set(key, silent)
		-- KeyCode 0 is "Unknown" on older clients and "None" on newer ones
		local shown = tostring(key)
		if shown == "Enum.KeyCode.Unknown" or shown == "Enum.KeyCode.None" then
			key = nil
		end
		local changed = key ~= self.Value
		self.Value = key
		valueLabel.Text = keyName(key)
		valueLabel.TextColor3 = Theme.Text
		if self.Flag then
			Lunar.Flags[self.Flag] = key
		end
		if changed and not silent then
			self:_fire()
		end
	end

	local function stop()
		listening = false
		self.Window._capturing = false
		tween(border, 0.25, { Color = Theme.ControlStroke })
		tween(chevron, 0.25, { Rotation = 0 })
	end

	beginCapture = function()
		if listening then
			return
		end
		self.Window:_closePopup()
		listening = true
		self.Window._capturing = true
		valueLabel.Text = "Press a key"
		valueLabel.TextColor3 = Theme.Accent
		tween(border, 0.15, { Color = Theme.Accent })
		tween(chevron, 0.25, { Rotation = 180 })
		-- skip the click that started the capture
		local armed = false
		task.delay(0.12, function()
			armed = true
		end)
		local conn
		conn = connect(UserInputService.InputBegan, function(input)
			if not listening then
				conn:Disconnect()
				return
			end
			if not armed then
				return
			end
			local key
			if input.UserInputType == Enum.UserInputType.Keyboard then
				if input.KeyCode == Enum.KeyCode.Escape then
					conn:Disconnect()
					stop()
					self:Set(self.Value, true)
					return
				elseif input.KeyCode == Enum.KeyCode.Backspace then
					key = nil
				else
					key = input.KeyCode
				end
			elseif
				input.UserInputType == Enum.UserInputType.MouseButton1
				or input.UserInputType == Enum.UserInputType.MouseButton2
				or input.UserInputType == Enum.UserInputType.MouseButton3
			then
				key = input.UserInputType
			else
				return
			end
			conn:Disconnect()
			stop()
			self:Set(key)
		end)
	end

	connect(UserInputService.InputBegan, function(input, processed)
		if listening or processed or self.Value == nil or not self.Pressed then
			return
		end
		if input.KeyCode == self.Value or input.UserInputType == self.Value then
			safeCall(self.Pressed, self.Value)
		end
	end)

	self:Set(cfg.Default, true)
	self.Default = self.Value
	return self
end

