local function keyName(key)
	if key == nil then
		return "None"
	end
	local name = typeof(key) == "EnumItem" and key.Name or tostring(key)
	if KEY_NAMES[name] then
		return KEY_NAMES[name]
	end
	-- "PageUp" -> "Page Up", "Q" -> "Q"
	return (string.gsub(name, "(%l)(%u)", "%1 %2"))
end

