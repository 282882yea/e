local function colorSeq(...)
	local points = { ... }
	if #points == 2 and typeof(points[1]) == "Color3" then
		return ColorSequence.new(points[1], points[2])
	end
	local keys = {}
	for i = 1, #points, 2 do
		table.insert(keys, ColorSequenceKeypoint.new(points[i], points[i + 1]))
	end
	return ColorSequence.new(keys)
end

local function numberSeq(...)
	local points = { ... }
	local keys = {}
	for i = 1, #points, 2 do
		table.insert(keys, NumberSequenceKeypoint.new(points[i], points[i + 1]))
	end
	return NumberSequence.new(keys)
end

