local function base64Decode(data)
	local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	local lut = table.create(256, 0)
	for i = 1, 64 do
		lut[string.byte(alphabet, i) + 1] = i - 1
	end
	local len = #data
	local pad = 0
	if string.sub(data, -2) == "==" then
		pad = 2
	elseif string.sub(data, -1) == "=" then
		pad = 1
	end
	local outLen = math.floor(len / 4) * 3 - pad

	if buffer then
		local src = buffer.fromstring(data)
		local out = buffer.create(outLen)
		local o = 0
		for i = 0, len - 4, 4 do
			local n = lut[buffer.readu8(src, i) + 1] * 262144
				+ lut[buffer.readu8(src, i + 1) + 1] * 4096
				+ lut[buffer.readu8(src, i + 2) + 1] * 64
				+ lut[buffer.readu8(src, i + 3) + 1]
			if o < outLen then
				buffer.writeu8(out, o, bit32.band(bit32.rshift(n, 16), 255))
			end
			if o + 1 < outLen then
				buffer.writeu8(out, o + 1, bit32.band(bit32.rshift(n, 8), 255))
			end
			if o + 2 < outLen then
				buffer.writeu8(out, o + 2, bit32.band(n, 255))
			end
			o += 3
		end
		return buffer.tostring(out)
	end

	local parts = {}
	local chunk = {}
	local o = 0
	for i = 1, len - 3, 4 do
		local a, b, c, d = string.byte(data, i, i + 3)
		local n = lut[a + 1] * 262144 + lut[b + 1] * 4096 + lut[c + 1] * 64 + lut[d + 1]
		for shift = 16, 0, -8 do
			if o < outLen then
				chunk[#chunk + 1] = string.char(bit32.band(bit32.rshift(n, shift), 255))
				o += 1
			end
		end
		if #chunk >= 3000 then
			parts[#parts + 1] = table.concat(chunk)
			chunk = {}
		end
	end
	parts[#parts + 1] = table.concat(chunk)
	return table.concat(parts)
end

local function loadAssets(overrides, folder)
	local getasset = getcustomasset or getsynasset
	local canWrite = type(writefile) == "function" and type(getasset) == "function"
	local files = EMBEDDED.files or {}
	local dir = folder .. "/assets-" .. tostring(EMBEDDED.version or "dev")

	if canWrite and type(makefolder) == "function" then
		pcall(makefolder, folder)
		pcall(makefolder, dir)
	end

	local function fromFile(path, bytes)
		if not canWrite then
			return nil
		end
		local ok, id = pcall(function()
			local exists = type(isfile) == "function" and isfile(path)
			if not exists and bytes then
				writefile(path, bytes())
			end
			return getasset(path)
		end)
		return ok and id or nil
	end

	local names = { "background", "blossoms", "flowers_left", "flowers_right", "petal", "glow", "icons" }
	for _, name in ipairs(names) do
		local override = overrides and overrides[name]
		local id
		if type(override) == "string" then
			if string.find(override, "^https?://") then
				-- remote image: download once into the workspace
				id = fromFile(dir .. "/" .. name .. "-custom.png", function()
					return game:HttpGet(override)
				end)
			elseif string.find(override, "^rbx") then
				id = override
			else
				id = fromFile(override, nil) -- a file already in the workspace
			end
		elseif override ~= false and files[name] then
			id = fromFile(dir .. "/" .. name .. ".png", function()
				return base64Decode(files[name])
			end)
		end
		Assets[name] = id or ""
	end
end

local function setIcon(image, name)
	if type(name) ~= "string" or name == "" then
		image.Image = ""
		return
	end
	if string.find(name, "^rbx") or string.find(name, "^http") then
		image.Image = name
		image.ImageRectOffset = Vector2.new(0, 0)
		image.ImageRectSize = Vector2.new(0, 0)
		return
	end
	local cell = ICONS[name]
	if cell and Assets.icons ~= "" then
		image.Image = Assets.icons
		image.ImageRectOffset = Vector2.new(cell[1], cell[2])
		image.ImageRectSize = Vector2.new(ICON_CELL, ICON_CELL)
	else
		image.Image = ""
	end
end

local function icon(name, size, color, props)
	local image = new("ImageLabel", {
		Name = "Icon",
		Size = UDim2.fromOffset(size, size),
		ImageColor3 = color or WHITE,
		ScaleType = Enum.ScaleType.Fit,
	})
	setIcon(image, name)
	if props then
		for key, value in pairs(props) do
			image[key] = value
		end
	end
	return image
end

