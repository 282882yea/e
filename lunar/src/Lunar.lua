local function tween(instance, time, props, style, direction)
	local t = TweenService:Create(instance, TweenInfo.new(time, style or EASE, direction or OUT), props)
	t:Play()
	return t
end

local function trySet(instance, prop, value)
	return pcall(function()
		instance[prop] = value
	end)
end

local function new(class, props, children)
	local inst = Instance.new(class)
	if inst:IsA("GuiObject") then
		inst.BorderSizePixel = 0
		if class ~= "Frame" and class ~= "ScrollingFrame" then
			inst.BackgroundTransparency = 1
		end
		if class == "TextButton" or class == "ImageButton" then
			inst.AutoButtonColor = false
		end
		if class == "TextButton" then
			inst.Text = ""
		end
	end
	local parent
	if props then
		for key, value in pairs(props) do
			if key == "Parent" then
				parent = value
			else
				inst[key] = value
			end
		end
	end
	if children then
		for _, child in ipairs(children) do
			child.Parent = inst
		end
	end
	if parent then
		inst.Parent = parent
	end
	return inst
end

local function px(n)
