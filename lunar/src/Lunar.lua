	task.delay(cfg.Duration or 4, function()
		if toast.Parent then
			fade(toast, false, 0.3, function()
				toast:Destroy()
			end)
		end
	end)
end

---------------------------------------------------------------------
-- Teardown
---------------------------------------------------------------------

function Lunar:Unload()
	if Lunar.Unloaded then
		return
	end
	Lunar.Unloaded = true
	safeCall(Lunar.OnUnload)
	for _, conn in ipairs(Lunar._connections) do
		conn:Disconnect()
	end
	for _, window in ipairs(Lunar._windows) do
		if window._alive then
			window:Destroy()
		end
	end
	table.clear(Lunar._connections)
	table.clear(Lunar._windows)
end

Lunar.Icons = ICONS

return Lunar
