		FontFace = Fonts.Body,
		TextSize = 15,
		TextColor3 = Theme.SubText,
		TextXAlignment = Enum.TextXAlignment.Left,
		TextYAlignment = Enum.TextYAlignment.Top,
		TextWrapped = true,
		Text = cfg.Content or cfg.Text or "",
		Parent = column,
	})

