			self._size = Vector2.new(width, height)
			root.Size = UDim2.fromOffset(width, height)
		end, function()
			self:_fit()
		end)
	end)

	connect(UserInputService.InputChanged, function(input)
		local drag = self._drag
		if drag and isMove(input) then
			drag.Move(input.Position)
		end
	end)
	connect(UserInputService.InputEnded, function(input)
		local drag = self._drag
		if drag and isPress(input) then
			self._drag = nil
			if drag.End then
				drag.End()
			end
		end
	end)

	-- keyboard -----------------------------------------------------------
	connect(UserInputService.InputBegan, function(input, processed)
		if not self._alive or input.UserInputType ~= Enum.UserInputType.Keyboard then
			return
		end
		if self._capturing then
			return
		end
		if input.KeyCode == self.ToggleKey and not UserInputService:GetFocusedTextBox() then
			self:Toggle()
			return
		end
		if input.KeyCode == Enum.KeyCode.K and self.Visible then
			local held = UserInputService:IsKeyDown(Enum.KeyCode.LeftControl)
				or UserInputService:IsKeyDown(Enum.KeyCode.RightControl)
				or UserInputService:IsKeyDown(Enum.KeyCode.LeftMeta)
				or UserInputService:IsKeyDown(Enum.KeyCode.RightMeta)
			if held then
				-- wait a frame so the "k" keystroke is not typed into the box
				task.defer(function()
					RunService.RenderStepped:Wait()
					search:CaptureFocus()
				end)
			end
		elseif input.KeyCode == Enum.KeyCode.Escape and self._popup then
			self:_closePopup()
		end
	end)

	local camera = workspace.CurrentCamera
	if camera then
		connect(camera:GetPropertyChangedSignal("ViewportSize"), function()
			self:_fit()
		end)
	end
	self._pages:GetPropertyChangedSignal("AbsoluteSize"):Connect(function()
		self._trackHeight = self._pages.AbsoluteSize.Y / self._scale - 3
		self:_updateThumb()
	end)

	-- mount --------------------------------------------------------------
	local mounted = false
	if type(gethui) == "function" then
		mounted = pcall(function()
			gui.Parent = gethui()
		end)
	end
	if not mounted then
		mounted = pcall(function()
			gui.Parent = service("CoreGui")
		end)
	end
	if not mounted then
		gui.Parent = Players.LocalPlayer:WaitForChild("PlayerGui")
	end

	if cfg.Petals ~= false then
		spawnPetals(self, petals, cfg.PetalCount or 9)
	end
	if cfg.Twinkle ~= false and EMBEDDED.sparkles then
		spawnTwinkles(self, leftArt, EMBEDDED.sparkles.flowers_left, 2)
		spawnTwinkles(self, rightArt, EMBEDDED.sparkles.flowers_right, 2)
	end
	self:_loop(aura, 0.84, 3.2)

	table.insert(Lunar._windows, self)

	-- intro: fade and settle into place
	if cfg.Intro ~= false then
		self.Visible = false
		root.Visible = false
		task.defer(function()
			if self._alive then
				self:SetVisible(true)
			end
		end)
	elseif self._blur then
		self._blur:SetEnabled(true)
	end
	return self
end

