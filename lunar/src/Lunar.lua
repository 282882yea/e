		if isPress(input_) then
			setActive(true)
			fromX(input_.Position.X)
			self.Window:_beginDrag(function(position)
				fromX(position.X)
			end, function()
				setActive(false)
			end)
		end
	end)
	track.MouseEnter:Connect(function()
		setGlow(halo, 0.3, 0.15)
	end)
	track.MouseLeave:Connect(function()
		if not self.Window._drag then
			setGlow(halo, 0.5, 0.25)
		end
	end)

