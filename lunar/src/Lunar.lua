function Window:SelectTab(page, instant)
	local previous = self.Current
	if previous == page then
		return
	end
	self:_closePopup()
	self.Current = page

	if previous then
		fadeFinish(previous._scroll)
		previous._scroll.Visible = false
		tween(previous._navLabel, 0.25, { TextColor3 = Theme.TextNav })
		tween(previous._navIcon, 0.25, { ImageColor3 = Theme.TextNav })
	end

	local pill = self._pill
	local target = UDim2.fromOffset(4, page._navTop - 4)
	pill.Visible = true
	if instant then
		pill.Position = target
		page._navLabel.TextColor3 = Theme.TextBright
		page._navIcon.ImageColor3 = Theme.TextBright
		page._scroll.Visible = true
	else
		tween(pill, 0.42, { Position = target }, Enum.EasingStyle.Back)
		tween(page._navLabel, 0.2, { TextColor3 = Theme.TextBright })
		tween(page._navIcon, 0.2, { ImageColor3 = Theme.TextBright })
		-- slide the new page up into place while it fades in
		page._scroll.CanvasPosition = Vector2.new(0, 0)
		page._grid.Position = UDim2.fromOffset(GRID_LEFT, GRID_TOP + 16)
		tween(page._grid, 0.4, { Position = UDim2.fromOffset(GRID_LEFT, GRID_TOP) })
		fade(page._scroll, true, 0.22)
	end

	self._crumb.Text = page.Name
	if self._search.Text ~= "" then
		self._search.Text = ""
	else
		page:_filter("")
	end
	self:_updateThumb()
	safeCall(self.OnTabChanged, page)
end

-- Endless "breathing" tweens. A fade tweens the same properties, which cancels them,
-- so they are restarted from their base value whenever a fade finishes.
function Window:_loop(handle, peak, period)
	if not handle or not handle.Instance then
		return
	end
	local entry = {
		Instance = handle.Instance,
		Property = handle.Property,
		Base = handle.Instance[handle.Property],
		Tween = TweenService:Create(
			handle.Instance,
			TweenInfo.new(period, Enum.EasingStyle.Sine, Enum.EasingDirection.InOut, -1, true),
			{ [handle.Property] = peak }
		),
	}
	table.insert(self._loops, entry)
	entry.Tween:Play()
end

function Window:_restartLoops()
	for _, entry in ipairs(self._loops) do
		entry.Tween:Cancel()
		entry.Instance[entry.Property] = entry.Base
		entry.Tween:Play()
	end
end

function Window:SetVisible(visible)
	if self.Visible == visible then
		return
	end
	self.Visible = visible
	self:_closePopup()
	local root = self._root
	local scaler = self._scaler
	if visible then
		if self._blur then
			self._blur:SetEnabled(true)
		end
		scaler.Scale = self._scale * 0.955
		tween(scaler, 0.38, { Scale = self._scale }, Enum.EasingStyle.Back)
		for _, entry in ipairs(self._loops) do
			entry.Tween:Cancel()
			entry.Instance[entry.Property] = entry.Base
		end
		fade(root, true, 0.24, function()
			self:_restartLoops()
		end)
	else
		tween(scaler, 0.2, { Scale = self._scale * 0.97 }, Enum.EasingStyle.Quad)
		fade(root, false, 0.18, function()
			if self._blur and not self.Visible then
				self._blur:SetEnabled(false)
			end
		end)
	end
end

function Window:Toggle()
	self:SetVisible(not self.Visible)
end

function Window:SetScale(scale)
	self._userScale = scale
	self:_fit()
end

function Window:_fit()
	local camera = workspace.CurrentCamera
	local viewport = camera and camera.ViewportSize or Vector2.new(1920, 1080)
	local size = self._size
	-- never larger than the screen, otherwise exactly the requested scale
	local fit = math.min((viewport.X - 16) / size.X, (viewport.Y - 16) / size.Y)
	local scale = math.clamp(math.min(self._userScale, fit), 0.35, 3)
	self._scale = scale
	self._scaler.Scale = scale
end

function Window:SetStatus(text)
	self._status.Text = text
end

function Window:Destroy()
	self:_closePopup()
	if self._blur then
		self._blur:Destroy()
	end
	self._alive = false
	self._gui:Destroy()
end

local function spawnPetals(window, layer, count)
	if Assets.petal == "" then
		return
	end
	for i = 1, count do
		task.spawn(function()
			local rng = Random.new(os.clock() * 1000 + i * 977)
			task.wait(rng:NextNumber(0, 9))
			while window._alive do
				local fromLeft = rng:NextNumber() < 0.45
				local startX = fromLeft and rng:NextNumber(0.01, 0.1) or rng:NextNumber(0.86, 0.99)
				local startY = rng:NextNumber(40, 150)
				local fall = rng:NextNumber(260, 430)
				local drift = rng:NextNumber(-90, 90) + (fromLeft and 60 or -60)
				local life = rng:NextNumber(7, 12)
				local size = rng:NextInteger(1, 2) * 7

				local holder = new("Frame", {
					Position = UDim2.new(startX, 0, 0, startY),
					Size = UDim2.fromOffset(1, 1),
					BackgroundTransparency = 1,
					Parent = layer,
				})
				local petal = new("ImageLabel", {
					AnchorPoint = Vector2.new(0.5, 0.5),
					Size = UDim2.fromOffset(size, size * 6 / 7),
					Image = Assets.petal,
					ImageTransparency = 1,
					ResampleMode = Enum.ResamplerMode.Pixelated,
					Rotation = rng:NextNumber(0, 360),
					Parent = holder,
				})
				local visible = window.Visible
				tween(holder, life, { Position = UDim2.new(startX, drift, 0, startY + fall) }, Enum.EasingStyle.Sine, Enum.EasingDirection.In)
				-- sideways flutter on the inner image, falling on the holder
				local sway = TweenService:Create(
					petal,
					TweenInfo.new(rng:NextNumber(1.4, 2.4), Enum.EasingStyle.Sine, Enum.EasingDirection.InOut, -1, true),
					{ Position = UDim2.fromOffset(rng:NextNumber(14, 30), 0), Rotation = petal.Rotation + rng:NextNumber(-120, 120) }
				)
				sway:Play()
				if visible then
					tween(petal, 1.2, { ImageTransparency = rng:NextNumber(0.25, 0.5) }, Enum.EasingStyle.Quad)
				end
				task.wait(life - 1.6)
				tween(petal, 1.5, { ImageTransparency = 1 }, Enum.EasingStyle.Quad)
				task.wait(1.6)
				sway:Cancel()
				holder:Destroy()
				task.wait(rng:NextNumber(1, 6))
			end
		end)
	end
end

local function spawnTwinkles(window, image, points, pixel)
	if not points or #points == 0 then
		return
	end
	for i = 1, 5 do
		task.spawn(function()
			local rng = Random.new(os.clock() * 1000 + i * 131)
			task.wait(rng:NextNumber(0, 3))
			while window._alive do
				local point = points[rng:NextInteger(1, #points)]
				local star = new("Frame", {
					AnchorPoint = Vector2.new(0.5, 0.5),
					Position = UDim2.fromOffset(point[1] * pixel + pixel / 2, point[2] * pixel + pixel / 2),
					Size = UDim2.fromOffset(pixel, pixel),
					BackgroundColor3 = rgb(255, 236, 246),
					BackgroundTransparency = 1,
					Parent = image,
				})
				local arms = {}
				for _, offset in ipairs({ { 1, 0 }, { -1, 0 }, { 0, 1 }, { 0, -1 } }) do
					table.insert(arms, new("Frame", {
						Position = UDim2.fromOffset(offset[1] * pixel, offset[2] * pixel),
						Size = UDim2.fromOffset(pixel, pixel),
						BackgroundColor3 = rgb(255, 190, 222),
						BackgroundTransparency = 1,
						Parent = star,
					}))
				end
				if window.Visible then
					tween(star, 0.5, { BackgroundTransparency = 0 }, Enum.EasingStyle.Sine)
					for _, arm in ipairs(arms) do
						tween(arm, 0.5, { BackgroundTransparency = 0.25 }, Enum.EasingStyle.Sine)
					end
				end
				task.wait(rng:NextNumber(0.6, 1.1))
				tween(star, 0.6, { BackgroundTransparency = 1 }, Enum.EasingStyle.Sine)
				for _, arm in ipairs(arms) do
					tween(arm, 0.6, { BackgroundTransparency = 1 }, Enum.EasingStyle.Sine)
				end
				task.wait(0.65)
				star:Destroy()
				task.wait(rng:NextNumber(0.4, 2.2))
			end
		end)
	end
end

