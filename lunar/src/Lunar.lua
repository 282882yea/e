function Window:_updateThumb()
	local page = self.Current
	local thumb = self._thumb
	if not page then
		thumb.Visible = false
		return
	end
	local scroll = page._scroll
	local view = scroll.AbsoluteWindowSize.Y
	local canvas = scroll.AbsoluteCanvasSize.Y
	if view <= 0 or canvas <= view + 1 then
		thumb.Visible = false
		return
	end
	local track = (self._trackHeight or 0)
	if track <= 0 then
		track = view / self._scale - 2
	end
	local length = math.max(28, track * view / canvas)
	local progress = math.clamp(scroll.CanvasPosition.Y / (canvas - view), 0, 1)
	thumb.Visible = true
	thumb.Size = UDim2.fromOffset(6, round(length))
	thumb.Position = UDim2.new(1, -9, 0, TOPBAR + 2 + round((track - length) * progress))
end

