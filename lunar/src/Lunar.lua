function Lunar:Notify(cfg)
	local window = Lunar._windows[#Lunar._windows]
	if not window or not window._alive then
		return
	end
	local gui = window._gui
	local holder = gui:FindFirstChild("Toasts")
	if not holder then
		holder = new("Frame", {
			Name = "Toasts",
			AnchorPoint = Vector2.new(1, 1),
			Position = UDim2.new(1, -18, 1, -18),
			Size = UDim2.fromOffset(300, 0),
			AutomaticSize = Enum.AutomaticSize.Y,
			BackgroundTransparency = 1,
			Parent = gui,
		})
		new("UIListLayout", {
			SortOrder = Enum.SortOrder.LayoutOrder,
			VerticalAlignment = Enum.VerticalAlignment.Bottom,
			Padding = px(10),
			Parent = holder,
		})
	end

	window._toasts = (window._toasts or 0) + 1
	local toast = new("Frame", {
		Name = "Toast",
		LayoutOrder = window._toasts,
		Size = UDim2.new(1, 0, 0, 0),
		AutomaticSize = Enum.AutomaticSize.Y,
		BackgroundColor3 = WHITE,
		BackgroundTransparency = 0,
		Visible = false,
		Parent = holder,
	})
	corner(toast, 13)
	gradient(toast, 90, colorSeq(Theme.HeaderTop, Theme.BodyMid), numberSeq(0, 0.04, 1, 0.04))
	local border = stroke(toast, WHITE, 1, 0)
	gradient(border, 90, colorSeq(Theme.CardStrokeTop, Theme.CardStrokeLow))
	glow(toast, { Color = Theme.Glow, Blur = 22, Transparency = 0.7 })
	icon(cfg.Icon or "sparkles", 16, Theme.Accent, { Name = "Badge", Position = UDim2.fromOffset(13, 13), Parent = toast })
