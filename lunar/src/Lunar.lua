function Page:_updateCount()
	local n = #self.Modules
	self._count.Text = n .. (n == 1 and " module" or " modules")
end

function Page:_queueLayout()
	if self._layoutQueued then
		return
	end
	self._layoutQueued = true
	task.defer(function()
		self._layoutQueued = false
		if not Lunar.Unloaded then
			self:_layout(false)
		end
	end)
end

-- Two columns; both cards in a row share the taller card's height.
function Page:_layout(animated)
	local visible = {}
	for _, module in ipairs(self.Modules) do
		module._card.Visible = not module._filtered
		if not module._filtered then
			table.insert(visible, module)
		end
	end
	local y = 0
	for i = 1, #visible, 2 do
		local a, b = visible[i], visible[i + 1]
		local heightA = a:_height()
		local heightB = b and b:_height() or 0
		local open = 0
		if not a.Collapsed then
			open = heightA
		end
		if b and not b.Collapsed then
			open = math.max(open, heightB)
		end
		a:_place(0, y, a.Collapsed and heightA or open, animated)
		if b then
			b:_place(1, y, b.Collapsed and heightB or open, animated)
		end
		y += math.max(open, heightA, heightB) + CARD_GAP_Y
	end
	local total = math.max(0, y - CARD_GAP_Y)
	self._grid.Size = UDim2.new(1, -(GRID_LEFT + GRID_RIGHT), 0, total)
	self._empty.Visible = #visible == 0 and #self.Modules > 0
	self._scroll.CanvasSize = UDim2.fromOffset(0, GRID_TOP + total + 12)
	self.Window:_updateThumb()
end

function Page:_filter(query)
	query = string.lower(query or "")
	for _, module in ipairs(self.Modules) do
		local titleHit = query == ""
			or string.find(string.lower(module.Title), query, 1, true) ~= nil
			or string.find(string.lower(module.Description), query, 1, true) ~= nil
		local any = titleHit
		for _, control in ipairs(module.Controls) do
			local hit = titleHit or string.find(string.lower(control.Name), query, 1, true) ~= nil
			control._filtered = not hit
			control.Row.Visible = hit and not control.Hidden
			any = any or hit
		end
		module._filtered = not any
	end
	self:_layout(false)
end

