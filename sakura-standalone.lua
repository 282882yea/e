local function safeCall(fn, ...)
	if type(fn) ~= "function" then
		return
	end
	task.spawn(function(...)
		local ok, err = pcall(fn, ...)
		if not ok then
			warn("[Sakura UI] callback error: " .. tostring(err))
		end
	end, ...)
end

local function isPress(input)
	return input.UserInputType == Enum.UserInputType.MouseButton1
		or input.UserInputType == Enum.UserInputType.Touch
end

-- Follows a press until it is released. `onMove` receives the pointer position.
local function trackDrag(startInput, onMove, onEnd)
	local moveConn, endConn
	moveConn = UserInputService.InputChanged:Connect(function(input)
		if input == startInput or input.UserInputType == Enum.UserInputType.MouseMovement then
			onMove(input.Position)
		end
	end)
	endConn = startInput.Changed:Connect(function()
		if startInput.UserInputState == Enum.UserInputState.End then
			moveConn:Disconnect()
			endConn:Disconnect()
			if onEnd then
				onEnd()
			end
		end
	end)
end

local function round(value, step)
	local result = math.floor(value / step + 0.5) * step
	-- trim float noise such as 0.30000000000000004
	return tonumber(string.format("%.6f", result))
end

local function colorToHex(color)
	return string.format(
		"%02X%02X%02X",
		math.floor(color.R * 255 + 0.5),
		math.floor(color.G * 255 + 0.5),
		math.floor(color.B * 255 + 0.5)
	)
end

local function hexToColor(hex)
	hex = string.gsub(tostring(hex), "#", "")
	local r, g, b = string.match(hex, "^(%x%x)(%x%x)(%x%x)$")
	if not r then
		return nil
	end
	return Color3.fromRGB(tonumber(r, 16), tonumber(g, 16), tonumber(b, 16))
end

local function mountGui(gui)
	if type(gethui) == "function" then
		local ok = pcall(function()
			gui.Parent = gethui()
		end)
		if ok then
			return
		end
	end
	if type(syn) == "table" and type(syn.protect_gui) == "function" then
		pcall(syn.protect_gui, gui)
	elseif type(protectgui) == "function" then
		pcall(protectgui, gui)
	end
	local ok = pcall(function()
		gui.Parent = CoreGui
	end)
	if not ok then
		-- No CoreGui access (e.g. running in Studio): fall back to PlayerGui.
		gui.Parent = Players.LocalPlayer:WaitForChild("PlayerGui")
	end
end

-- Three stacked ScreenGuis. The backdrop is thousands of static frames, so it
-- lives in its own gui and is not re-laid-out when the controls animate; the
-- glow sits below it so only the part outside the window shows.
local function getGuis()
	local guis = Library._guis
	if guis.main then
		return guis
	end
	for index, key in ipairs({ "glow", "back", "main" }) do
		local gui = create("ScreenGui", {
			Name = HttpService:GenerateGUID(false),
			ResetOnSpawn = false,
			IgnoreGuiInset = true,
			ZIndexBehavior = Enum.ZIndexBehavior.Sibling,
			DisplayOrder = 9000 + index,
		})
		mountGui(gui)
		guis[key] = gui
	end
	return guis
end

