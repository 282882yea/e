local ALPHABET = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
local DIGIT = {}
for i = 1, #ALPHABET do
	DIGIT[string.byte(ALPHABET, i)] = i - 1
end

local SKY_BANDS = 18
local ANCHOR_X = { l = 0, c = 0.5, r = 1 }

-- "RRGGBB" or "RRGGBBAA" -> Color3, transparency
local function hexColor(hex)
	local r = tonumber(string.sub(hex, 1, 2), 16)
	local g = tonumber(string.sub(hex, 3, 4), 16)
	local b = tonumber(string.sub(hex, 5, 6), 16)
	local alpha = 255
	if #hex >= 8 then
		alpha = tonumber(string.sub(hex, 7, 8), 16)
	end
	return Color3.fromRGB(r, g, b), 1 - alpha / 255
end

local function scenePalette(theme)
	local palette = theme.Scene
	if type(palette) == "string" then
		palette = SCENE_PALETTES[palette]
	end
	return palette or SCENE_PALETTES.Dusk
end

-- Sky colour for band `index`, blended across the palette's key colours.
local function skyColor(palette, index)
	local keys = palette.sky
	local t = (index - 1) / (SKY_BANDS - 1) * (#keys - 1)
	local k = math.min(#keys - 1, math.floor(t) + 1)
	local a = hexColor(keys[k])
	local b = hexColor(keys[k + 1])
	return a:Lerp(b, t - (k - 1))
end

-- Draws the backdrop into `parent`. Every rectangle in the generated data is
-- one Frame; `pixel` is the on-screen size of one art pixel.
local function buildScene(parent, pixel)
	local palette = scenePalette(Library.Theme)
	local scene = { _bands = {}, _strips = {}, _slots = {} }
	local holder = create("Frame", {
		Name = "Scene",
		Size = UDim2.fromScale(1, 1),
		BackgroundTransparency = 1,
	})
	scene.Instance = holder

	for i = 1, SKY_BANDS do
		scene._bands[i] = create("Frame", {
			Position = UDim2.fromScale(0, (i - 1) / SKY_BANDS),
			Size = UDim2.new(1, 0, 1 / SKY_BANDS, 1),
			BackgroundColor3 = skyColor(palette, i),
			Parent = holder,
		})
	end
	for i, strip in ipairs(SCENE_STRIPS) do
		scene._strips[i] = create("Frame", {
			Position = UDim2.new(0, 0, 1, -strip[1] * pixel),
			Size = UDim2.new(1, 0, 0, strip[2] * pixel),
			BackgroundColor3 = hexColor(palette[strip[3]]),
			Parent = holder,
		})
	end

	local colors, alphas = {}, {}
	for slot, name in ipairs(SCENE_SLOTS) do
		colors[slot], alphas[slot] = hexColor(palette[name])
		scene._slots[slot] = {}
	end
	for _, group in ipairs(SCENE_GROUPS) do
		local anchor, data = group[1], group[4]
		local ax = ANCHOR_X[string.sub(anchor, 2, 2)]
		local ay = string.sub(anchor, 1, 1) == "t" and 0 or 1
		local container = create("Frame", {
			AnchorPoint = Vector2.new(ax, ay),
			Position = UDim2.fromScale(ax, ay),
			Size = UDim2.fromOffset(group[2] * pixel, group[3] * pixel),
			BackgroundTransparency = 1,
			Parent = holder,
		})
		if type(data) == "table" then
			data = table.concat(data)
		end
		-- 7 characters per rectangle: x (2), y (2), width, height, palette slot.
		for i = 1, #data, 7 do
			local a, b, c, d, e, f, g = string.byte(data, i, i + 6)
			local slot = DIGIT[g] + 1
			local frame = Instance.new("Frame")
			frame.BorderSizePixel = 0
			frame.Position = UDim2.fromOffset((DIGIT[a] * 62 + DIGIT[b]) * pixel, (DIGIT[c] * 62 + DIGIT[d]) * pixel)
			frame.Size = UDim2.fromOffset(DIGIT[e] * pixel, DIGIT[f] * pixel)
			frame.BackgroundColor3 = colors[slot]
			frame.BackgroundTransparency = alphas[slot]
			frame.Parent = container
			local list = scene._slots[slot]
			list[#list + 1] = frame
		end
	end

	function scene:Recolor(newPalette)
		for i, band in ipairs(self._bands) do
			band.BackgroundColor3 = skyColor(newPalette, i)
		end
		for i, strip in ipairs(SCENE_STRIPS) do
			self._strips[i].BackgroundColor3 = hexColor(newPalette[strip[3]])
		end
		for slot, name in ipairs(SCENE_SLOTS) do
			local color, alpha = hexColor(newPalette[name])
			for _, frame in ipairs(self._slots[slot]) do
				frame.BackgroundColor3 = color
				frame.BackgroundTransparency = alpha
			end
		end
	end

	holder.Parent = parent
	return scene
end

-- Petals drifting across `layer`, snapped to the art-pixel grid.
local function startPetals(window, layer, width, height, pixel)
	local petals = { _items = {} }
	local shapes = { { 2, 1 }, { 1, 1 }, { 2, 2 }, { 1, 2 } }
	local slots = { "roseLight", "roseHi", "whiteLight", "whiteHi", "roseMid" }
	local clock = 0

	local function place(item, anywhere)
		item.x = math.random() * (width + 80) - 80
		item.y = anywhere and math.random() * height or -pixel * 2
		item.fall = 16 + math.random() * 22
		item.drift = 8 + math.random() * 16
		item.sway = 6 + math.random() * 10
		item.phase = math.random() * 6.28
	end

	function petals:Refresh()
		local settings = Library.Petals
		local palette = scenePalette(Library.Theme)
		local wanted = settings.Enabled and math.clamp(math.floor(settings.Count), 0, 60) or 0
		while #self._items > wanted do
			table.remove(self._items).frame:Destroy()
		end
		while #self._items < wanted do
			local shape = shapes[math.random(1, #shapes)]
			local item = {
				frame = create("Frame", {
					Size = UDim2.fromOffset(shape[1] * pixel, shape[2] * pixel),
					Parent = layer,
				}),
				slot = slots[math.random(1, #slots)],
			}
			place(item, true)
			table.insert(self._items, item)
		end
		for _, item in ipairs(self._items) do
			item.frame.BackgroundColor3 = hexColor(palette[item.slot])
		end
	end

	connect(RunService.Heartbeat, function(dt)
		if not window.Visible or window.Minimized then
			return
		end
		local speed = Library.Petals.Speed
		clock = clock + dt
		for _, item in ipairs(petals._items) do
			item.y = item.y + item.fall * speed * dt
			item.x = item.x + (item.drift + math.sin(clock * 1.7 + item.phase) * item.sway) * speed * dt
			if item.y > height or item.x > width then
				place(item, false)
			end
			local x = math.floor(item.x / pixel) * pixel
			local y = math.floor(item.y / pixel) * pixel
			if x ~= item.px or y ~= item.py then
				item.px, item.py = x, y
				item.frame.Position = UDim2.fromOffset(x, y)
			end
		end
	end)

	petals:Refresh()
	return petals
end

-- Library:SetPetals({ Enabled, Count, Speed })
function Library:SetPetals(settings)
	for key, value in pairs(settings or {}) do
		self.Petals[key] = value
	end
	for _, window in ipairs(self._windows) do
		window._petals:Refresh()
	end
end

