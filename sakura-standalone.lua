-- Builds a sprite out of frames: one per horizontal run of equal pixels,
-- stretched downwards while the rows below repeat the same run. Also returns
-- the frames grouped by sprite character, for recolouring.
local function sprite(rows, scale, colors)
	colors = colors or SPRITE_COLORS
	scale = scale or 1
	local height = #rows
	local width = #rows[1]
	local holder = create("Frame", {
		Size = UDim2.fromOffset(width * scale, height * scale),
		BackgroundTransparency = 1,
	})
	local parts = {}
	local open = {} -- ["x:w:char"] = frame still growing downwards
	for y = 1, height do
		local row = rows[y]
		local seen = {}
		local x = 1
		while x <= width do
			local char = string.sub(row, x, x)
			local run = 1
			while x + run <= width and string.sub(row, x + run, x + run) == char do
				run = run + 1
			end
			local color = colors[char]
			if color then
				local key = x .. ":" .. run .. ":" .. char
				local entry = open[key]
				if entry and entry.last == y - 1 then
					entry.rows = entry.rows + 1
					entry.last = y
					entry.frame.Size = UDim2.fromOffset(run * scale, entry.rows * scale)
				else
					entry = {
						rows = 1,
						last = y,
						frame = create("Frame", {
							Position = UDim2.fromOffset((x - 1) * scale, (y - 1) * scale),
							Size = UDim2.fromOffset(run * scale, scale),
							BackgroundColor3 = color,
							Parent = holder,
						}),
					}
					open[key] = entry
					parts[char] = parts[char] or {}
					table.insert(parts[char], entry.frame)
				end
				seen[key] = true
			end
			x = x + run
		end
		for key in pairs(open) do
			if not seen[key] then
				open[key] = nil
			end
		end
	end
	return holder, parts
end

