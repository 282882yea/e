local function tween(instance, info, props)
	local t = TweenService:Create(instance, info, props)
	t:Play()
	return t
end

-- Tweens when `animated`, otherwise sets the properties straight away.
local function apply(instance, animated, info, props)
	if animated then
		tween(instance, info, props)
	else
		for prop, value in pairs(props) do
			instance[prop] = value
		end
	end
end

local function connect(signal, fn)
	local conn = signal:Connect(fn)
	table.insert(Library._connections, conn)
	return conn
end

-- Sets theme-driven properties now and whenever the theme changes.
-- `map` is { PropertyName = "ThemeKey" }.
local function bind(instance, map)
	for prop, key in pairs(map) do
		instance[prop] = Library.Theme[key]
	end
	table.insert(Library._bindings, { instance, map })
	return instance
end

-- For state-dependent colours (e.g. a toggle that is accent only when on).
local function onTheme(fn)
	table.insert(Library._themeCallbacks, fn)
	fn(Library.Theme)
end

local function create(class, props, children)
	local instance = Instance.new(class)
	if GUI_CLASSES[class] then
		instance.BorderSizePixel = 0
	end
	local parent, theme
	for key, value in pairs(props or {}) do
		if key == "Parent" then
			parent = value
		elseif key == "Theme" then
			theme = value
		else
			instance[key] = value
		end
	end
	if theme then
		bind(instance, theme)
	end
	for _, child in ipairs(children or {}) do
		child.Parent = instance
	end
	if parent then
		instance.Parent = parent
	end
	return instance
end

-- True when `class` can be created and every property in `writes` accepts
-- the given value. New classes (UIShadow, UIBlur) can exist on a client
-- before all of their properties do.
local function canUse(class, writes)
	local ok, instance = pcall(Instance.new, class)
	if not ok or not instance then
		return false
	end
	local works = pcall(function()
		for property, value in pairs(writes) do
			instance[property] = value
		end
	end)
	pcall(function()
		instance:Destroy()
	end)
	return works
end

