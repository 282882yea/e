-- Logs a cosmetic failure once instead of letting it stop the window.
local reported = {}
local function soft(what, fn, ...)
	local ok, err = pcall(fn, ...)
	if not ok and not reported[what] then
		reported[what] = true
		warn("[Sakura UI] " .. what .. " failed, continuing without it: " .. tostring(err))
	end
	return ok
end

-- A sharp 1px border. `key` is a theme key, or nil for a stroke whose colour
-- the caller manages.
local function stroke(key)
	local instance = create("UIStroke", {
		ApplyStrokeMode = Enum.ApplyStrokeMode.Border,
		Thickness = 1,
	})
	pcall(function()
		instance.LineJoinMode = Enum.LineJoinMode.Miter
	end)
	if key ~= false then
		bind(instance, { Color = key or "Stroke" })
	end
	return instance
end

