local function applyTheme()
	local theme = Library.Theme
	for _, binding in ipairs(Library._bindings) do
		local instance, map = binding[1], binding[2]
		for prop, key in pairs(map) do
			instance[prop] = theme[key]
		end
	end
	for _, fn in ipairs(Library._themeCallbacks) do
		fn(theme)
	end
	for _, entry in ipairs(glows) do
		applyGlow(entry)
	end
end

-- Accepts a theme name or a table. Missing keys fall back to Dusk.
function Library:SetTheme(theme)
	local name
	if type(theme) == "string" then
		name = theme
		theme = self.Themes[theme]
	end
	if type(theme) ~= "table" then
		return
	end
	local resolved = {}
	for key, value in pairs(self.Themes.Dusk) do
		resolved[key] = value
	end
	for key, value in pairs(theme) do
		resolved[key] = value
	end
	if self._accent then
		resolved.Accent = self._accent
	end
	self._themeSource = theme
	self.ThemeName = name or self.ThemeName
	self.Theme = resolved
	applyTheme()
	local palette = scenePalette(resolved)
	for _, window in ipairs(self._windows) do
		window._scene:Recolor(palette)
		window._petals:Refresh()
	end
end

-- Overrides the theme's accent colour. Pass nil to go back to the theme's own.
function Library:SetAccent(color)
	self._accent = color
	self:SetTheme(self._themeSource or self.Themes[self.ThemeName] or self.Themes.Dusk)
end

