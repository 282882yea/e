end

function Tabbox:AddTab(name)
	local tabbox = self
	local body = create("Frame", {
		LayoutOrder = 4,
		Size = UDim2.new(1, 0, 0, 0),
		AutomaticSize = Enum.AutomaticSize.Y,
		BackgroundTransparency = 1,
		Visible = false,
		Parent = self.Instance,
	}, {
		padding(8, 10, 11, 10),
		create("UIListLayout", { SortOrder = Enum.SortOrder.LayoutOrder, Padding = UDim.new(0, 8) }),
	})
	local underline = create("Frame", {
		AnchorPoint = Vector2.new(0, 1),
		Position = UDim2.fromScale(0, 1),
		Size = UDim2.new(1, 0, 0, 1),
		Visible = false,
		Theme = { BackgroundColor3 = "Accent" },
	})
	local button = create("TextButton", {
		LayoutOrder = #self._tabs + 1,
		Size = UDim2.new(0, 0, 1, 0),
		AutomaticSize = Enum.AutomaticSize.X,
		BackgroundTransparency = 1,
		Font = FONT,
		TextSize = TEXT,
		Text = name or "tab",
		AutoButtonColor = false,
		Parent = self._row,
	}, { padding(0, 10), underline })
	local entry = { button = button, body = body, underline = underline, active = false }
	table.insert(self._tabs, entry)
	local function choose()
		for _, other in ipairs(tabbox._tabs) do
			local on = other == entry
			other.active = on
			other.body.Visible = on
			other.underline.Visible = on
			other.button.TextColor3 = on and Library.Theme.Accent or Library.Theme.SubText
		end
	end
	button.MouseButton1Click:Connect(choose)
	onTheme(function(theme)
		button.TextColor3 = entry.active and theme.Accent or theme.SubText
	end)
	if #self._tabs == 1 then
		choose()
	end
	return setmetatable({ Container = body, Instance = body, _order = 0 }, Groupbox)
end

-- `config` may be a name or { Name, Columns }.
function Tab:AddSubTab(config)
	if type(config) == "string" then
		config = { Name = config }
	end
	config = config or {}
	local tab = self
	local count = math.clamp(math.floor(config.Columns or self._window.Columns), 1, 4)

	local bullet = sprite(SPRITES.bloom, 1)
	bullet.AnchorPoint = Vector2.new(0, 0.5)
	bullet.Position = UDim2.new(0, -13, 0.5, 0)
	bullet.Visible = false
	local button = create("TextButton", {
		LayoutOrder = #self.SubTabs + 1,
		Size = UDim2.new(0, 0, 1, 0),
		AutomaticSize = Enum.AutomaticSize.X,
		BackgroundTransparency = 1,
		Font = FONT,
		TextSize = TEXT,
		Text = config.Name or "sub",
		AutoButtonColor = false,
		Parent = self._bar,
	}, { padding(0, 10, 0, 22), bullet })

	local page = create("Frame", {
		Size = UDim2.fromScale(1, 1),
		BackgroundTransparency = 1,
		Visible = false,
		Parent = self._page,
	})
	local columns = {}
	for i = 1, count do
		columns[i] = create("ScrollingFrame", {
			Position = UDim2.new((i - 1) / count, COLUMN_GAP - (i - 1) * COLUMN_GAP / count, 0, 0),
			Size = UDim2.new(1 / count, -COLUMN_GAP * (count + 1) / count, 1, 0),
			BackgroundTransparency = 1,
			ScrollBarThickness = 2,
			CanvasSize = UDim2.new(),
			AutomaticCanvasSize = Enum.AutomaticSize.Y,
			ScrollingDirection = Enum.ScrollingDirection.Y,
			Theme = { ScrollBarImageColor3 = "Accent" },
			Parent = page,
		}, {
			padding(11, 6, 12, 1),
			create("UIListLayout", { SortOrder = Enum.SortOrder.LayoutOrder, Padding = UDim.new(0, 11) }),
		})
	end

	local sub = setmetatable({
		Name = config.Name,
		Instance = page,
		_tab = self,
		_button = button,
		_bullet = bullet,
		_columns = columns,
		_counts = {},
		_active = false,
	}, SubTab)
	table.insert(self.SubTabs, sub)

	button.MouseButton1Click:Connect(function()
		tab:SelectSubTab(sub)
	end)
	onTheme(function(theme)
		button.TextColor3 = sub._active and theme.Accent or theme.SubText
	end)

	if #self.SubTabs == 1 then
		self:SelectSubTab(sub, true)
	end
	return sub
end

-- `instant` skips the colour tween.
function Tab:SelectSubTab(sub, instant)
	for _, other in ipairs(self.SubTabs) do
		local active = other == sub
		other._active = active
		other.Instance.Visible = active
		other._bullet.Visible = active
		apply(other._button, not instant, TWEEN_FAST, {
			TextColor3 = active and Library.Theme.Accent or Library.Theme.SubText,
		})
	end
end

