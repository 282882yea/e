local Window = {}
Window.__index = Window

local TITLE_HEIGHT, TAB_HEIGHT, SUB_HEIGHT, STATUS_HEIGHT = 28, 24, 22, 22
local BORDER = 2 -- outline + accent line

function Library:CreateWindow(config)
	config = config or {}
	if config.Theme then
		self:SetTheme(config.Theme)
	end
	local size = config.Size or UDim2.fromOffset(920, 580)
	local pixel = math.max(1, math.floor(config.PixelSize or 4))
	local guis = getGuis()

	local window = setmetatable({
		Tabs = {},
		ToggleKey = config.ToggleKey or Enum.KeyCode.RightShift,
		ConfigFolder = config.ConfigFolder or "SakuraUI",
		Columns = config.Columns or 2,
		Visible = true,
		Minimized = false,
		_size = size,
		_roots = {},
	}, Window)

	local function root(gui, props)
		props.AnchorPoint = CENTER
		props.Position = UDim2.fromScale(0.5, 0.5)
		props.Size = size
		props.Parent = gui
		local frame = create("Frame", props)
		table.insert(window._roots, frame)
		return frame
	end

	-- Layer 1: an opaque slab whose UIShadow is the window glow.
	local glowRoot = root(guis.glow, { Name = "Glow", Theme = { BackgroundColor3 = "Outline" } })
	window._glow = addGlow(glowRoot, "window")

	-- Layer 2: outline, accent line and the pixel-art backdrop.
	local backRoot = root(guis.back, { Name = "Backdrop", Theme = { BackgroundColor3 = "Outline" } })
	create("Frame", {
		Position = UDim2.fromOffset(1, 1),
		Size = UDim2.new(1, -2, 1, -2),
		Theme = { BackgroundColor3 = "Accent" },
		Parent = backRoot,
	})
	local sceneClip = create("Frame", {
		Position = UDim2.fromOffset(BORDER, BORDER),
		Size = UDim2.new(1, -BORDER * 2, 1, -BORDER * 2),
		ClipsDescendants = true,
		Theme = { BackgroundColor3 = "Panel" },
		Parent = backRoot,
	})
	local built, scene = pcall(buildScene, sceneClip, pixel)
	if not built then
		warn("[Sakura UI] backdrop failed, using a plain panel: " .. tostring(scene))
		scene = { Instance = create("Frame", { BackgroundTransparency = 1, Parent = sceneClip }) }
		function scene:Recolor() end
	end
	window._scene = scene
	window.Backdrop = sceneClip -- clipped frame behind the controls (custom images go here)
	window._scene.Instance.Visible = config.Background ~= false

	-- Layer 3: the controls.
	local shell = root(guis.main, { Name = "Window", BackgroundTransparency = 1 })
	window.Instance = shell
	local content = create("Frame", {
		Position = UDim2.fromOffset(BORDER, BORDER),
		Size = UDim2.new(1, -BORDER * 2, 1, -BORDER * 2),
		BackgroundTransparency = 1,
		ClipsDescendants = true,
		Active = true, -- stop clicks falling through to the game
		Parent = shell,
	})
	window._content = content
	-- A visible modal button frees the mouse in first-person games.
	create("TextButton", {
		Size = UDim2.new(),
		BackgroundTransparency = 1,
		Text = "",
		Modal = true,
		Parent = shell,
	})

	-- Scale: whatever SetScale asks for, shrunk so the window fits the screen.
	window._userScale = 1
	window._scales = {}
	for _, frame in ipairs(window._roots) do
		table.insert(window._scales, create("UIScale", { Scale = 1, Parent = frame }))
	end
	local camera = workspace and workspace.CurrentCamera
	function window:_rescale()
		local fit = 2
		if camera and size.X.Offset > 0 and size.Y.Offset > 0 then
			local viewport = camera.ViewportSize
			fit = math.min((viewport.X - 24) / size.X.Offset, (viewport.Y - 24) / size.Y.Offset)
		end
		local value = math.clamp(math.min(self._userScale, fit), 0.4, 2)
		for _, scale in ipairs(self._scales) do
			scale.Scale = value
		end
	end
	window:_rescale()
	if camera then
		connect(camera:GetPropertyChangedSignal("ViewportSize"), function()
			window:_rescale()
		end)
	end

	local petalLayer = create("Frame", {
		Size = UDim2.fromScale(1, 1),
		BackgroundTransparency = 1,
		ZIndex = 1,
		Parent = content,
	})
	window._petals = startPetals(
		window,
		petalLayer,
		math.max(size.X.Offset, 200) - BORDER * 2,
		math.max(size.Y.Offset, 200) - BORDER * 2,
		pixel
	)

	-- Title bar -----------------------------------------------------
	local titleBar = create("Frame", {
		Size = UDim2.new(1, 0, 0, TITLE_HEIGHT),
		ZIndex = 3,
		Theme = { BackgroundColor3 = "Header" },
		Parent = content,
	})
	glass(titleBar, "header")
	local icon = sprite(SPRITES.sakura, 2)
	icon.AnchorPoint = Vector2.new(0, 0.5)
	icon.Position = UDim2.new(0, 7, 0.5, 0)
	icon.Parent = titleBar
	local title = label({
		Position = UDim2.fromOffset(38, 0),
		Size = UDim2.new(0, 0, 1, 0),
		AutomaticSize = Enum.AutomaticSize.X,
		Text = config.Title or "sakura ui",
		Parent = titleBar,
	})
	addGlow(title, "text")
	if config.SubTitle then
		label({
			AnchorPoint = Vector2.new(1, 0),
			Position = UDim2.new(1, -62, 0, 0),
			Size = UDim2.new(0.5, 0, 1, 0),
			TextXAlignment = Enum.TextXAlignment.Right,
			Text = config.SubTitle,
			Theme = { TextColor3 = "SubText" },
			Parent = titleBar,
		})
	end

	local function topButton(text, offset, callback)
		local border = stroke()
		local button = create("TextButton", {
			AnchorPoint = Vector2.new(1, 0.5),
			Position = UDim2.new(1, offset, 0.5, 0),
			Size = UDim2.fromOffset(18, 16),
			Font = FONT,
			TextSize = TEXT,
			Text = text,
			AutoButtonColor = false,
			Theme = { BackgroundColor3 = "Element", TextColor3 = "Text" },
			Parent = titleBar,
		}, { border })
		hoverStroke(button, border)
		button.MouseButton1Click:Connect(callback)
		return button
	end
	topButton("x", -7, function()
		window:SetVisible(false)
	end)
	topButton("-", -31, function()
		window:SetMinimized(not window.Minimized)
	end)

	-- Dragging ------------------------------------------------------
	titleBar.InputBegan:Connect(function(input)
		if not isPress(input) then
			return
		end
		local origin = input.Position
		local start = shell.Position
		trackDrag(input, function(position)
			local delta = position - origin
			local moved = UDim2.new(start.X.Scale, start.X.Offset + delta.X, start.Y.Scale, start.Y.Offset + delta.Y)
			for _, frame in ipairs(window._roots) do
				frame.Position = moved
			end
		end)
	end)

	-- Tab bar, sub-tab bar and pages ---------------------------------
	local tabBar = create("Frame", {
		Position = UDim2.fromOffset(0, TITLE_HEIGHT),
		Size = UDim2.new(1, 0, 0, TAB_HEIGHT),
		ZIndex = 3,
		Theme = { BackgroundColor3 = "Header" },
		Parent = content,
	})
	glass(tabBar, "header")
	create("Frame", {
		Size = UDim2.new(1, 0, 0, 1),
		Theme = { BackgroundColor3 = "Stroke" },
		Parent = tabBar,
	})
	window._tabList = create("Frame", {
		Position = UDim2.fromOffset(0, 1),
		Size = UDim2.new(1, 0, 1, -1),
		BackgroundTransparency = 1,
		Parent = tabBar,
	}, {
		padding(0, 6),
		create("UIListLayout", {
			FillDirection = Enum.FillDirection.Horizontal,
			SortOrder = Enum.SortOrder.LayoutOrder,
		}),
	})

	local subBar = create("Frame", {
		Position = UDim2.fromOffset(0, TITLE_HEIGHT + TAB_HEIGHT),
		Size = UDim2.new(1, 0, 0, SUB_HEIGHT),
		ZIndex = 3,
		Theme = { BackgroundColor3 = "Panel" },
		Parent = content,
	})
	glass(subBar, "panel")
	create("Frame", {
		Size = UDim2.new(1, 0, 0, 1),
		Theme = { BackgroundColor3 = "Accent" },
		Parent = subBar,
	})
	create("Frame", {
		AnchorPoint = Vector2.new(0, 1),
		Position = UDim2.fromScale(0, 1),
		Size = UDim2.new(1, 0, 0, 1),
		Theme = { BackgroundColor3 = "Stroke" },
		Parent = subBar,
	})
	window._subBar = subBar

	local top = TITLE_HEIGHT + TAB_HEIGHT + SUB_HEIGHT
	window._pages = create("Frame", {
		Position = UDim2.fromOffset(0, top),
		Size = UDim2.new(1, 0, 1, -top - STATUS_HEIGHT),
		BackgroundTransparency = 1,
		ZIndex = 2,
		Parent = content,
	})

	-- Status bar ----------------------------------------------------
	local statusBar = create("Frame", {
		AnchorPoint = Vector2.new(0, 1),
		Position = UDim2.fromScale(0, 1),
		Size = UDim2.new(1, 0, 0, STATUS_HEIGHT),
		ZIndex = 3,
		Theme = { BackgroundColor3 = "Header" },
		Parent = content,
	})
	glass(statusBar, "header")
	create("Frame", {
		Size = UDim2.new(1, 0, 0, 1),
		Theme = { BackgroundColor3 = "Stroke" },
		Parent = statusBar,
	})
	local rose = sprite(SPRITES.rose, 2)
	rose.AnchorPoint = Vector2.new(0, 0.5)
	rose.Position = UDim2.new(0, 7, 0.5, 1)
	rose.Parent = statusBar
	label({
		Position = UDim2.fromOffset(33, 0),
		Size = UDim2.new(0.6, -33, 1, 0),
		Text = config.Footer or ("sakura ui v" .. Library.Version),
		TextTruncate = Enum.TextTruncate.AtEnd,
		Theme = { TextColor3 = "SubText" },
		Parent = statusBar,
	})
	window._hint = label({
		AnchorPoint = Vector2.new(1, 0),
		Position = UDim2.new(1, -8, 0, 0),
		Size = UDim2.new(0.4, -8, 1, 0),
		TextXAlignment = Enum.TextXAlignment.Right,
		Theme = { TextColor3 = "SubText" },
		Parent = statusBar,
	})
	window:SetToggleKey(window.ToggleKey)

	-- Toggle key ------------------------------------------------------
	connect(UserInputService.InputBegan, function(input, processed)
		if processed or Library._listening then
			return
		end
		if input.KeyCode == window.ToggleKey and input.KeyCode ~= Enum.KeyCode.Unknown then
			window:SetVisible(not window.Visible)
		end
	end)

	-- Touch devices have no toggle key, so give them a button.
	if UserInputService.TouchEnabled and not UserInputService.KeyboardEnabled then
		local mobile = create("TextButton", {
			Position = UDim2.new(0, 12, 0.5, -20),
			Size = UDim2.fromOffset(40, 40),
			Text = "",
			AutoButtonColor = false,
			Theme = { BackgroundColor3 = "Header" },
			Parent = guis.main,
		}, { stroke("Accent") })
		local flower = sprite(SPRITES.sakura, 2)
		flower.AnchorPoint = CENTER
		flower.Position = UDim2.fromScale(0.5, 0.5)
		flower.Parent = mobile
		mobile.MouseButton1Click:Connect(function()
			window:SetVisible(not window.Visible)
		end)
	end

	-- Glow pulse: breathe the window glow's opacity.
	local clock = 0
	connect(RunService.Heartbeat, function(dt)
		local settings = Library.Glow
		if not (window._glow and window.Visible and settings.Enabled and settings.Pulse) then
			return
		end
		clock = clock + dt
		applyGlow(window._glow, 0.8 + 0.2 * math.sin(clock * 2.4))
	end)

	table.insert(self._windows, window)

	-- Intro animation
	for _, frame in ipairs(window._roots) do
		frame.Size = UDim2.new(size.X.Scale, size.X.Offset, 0, TITLE_HEIGHT + BORDER * 2)
		tween(frame, TWEEN_MED, { Size = size })
	end

	return window
end

-- Window scale in percent (40-200). It still shrinks to fit the screen.
function Window:SetScale(percent)
	self._userScale = math.clamp((tonumber(percent) or 100) / 100, 0.4, 2)
	self:_rescale()
end

function Window:SetVisible(visible)
	self.Visible = visible
	for _, frame in ipairs(self._roots) do
		frame.Visible = visible
	end
end

function Window:Toggle()
	self:SetVisible(not self.Visible)
end

function Window:SetMinimized(minimized)
	self.Minimized = minimized
	local size = self._size
	local target = minimized and UDim2.new(size.X.Scale, size.X.Offset, 0, TITLE_HEIGHT + BORDER * 2) or size
	for _, frame in ipairs(self._roots) do
		tween(frame, TWEEN_MED, { Size = target })
	end
end

-- Shows or hides the pixel-art backdrop (a plain panel colour is left behind).
function Window:SetBackground(enabled)
	self._scene.Instance.Visible = enabled == true
end

function Window:SetToggleKey(key)
	if type(key) == "string" then
		local ok, code = pcall(function()
			return Enum.KeyCode[key]
		end)
		key = ok and code or Enum.KeyCode.Unknown
	end
	self.ToggleKey = key or Enum.KeyCode.Unknown
	if self.ToggleKey == Enum.KeyCode.Unknown then
		self._hint.Text = ""
	else
		self._hint.Text = "[" .. self.ToggleKey.Name .. "] hide"
	end
end

-- `instant` skips the colour tween.
function Window:SelectTab(tab, instant)
	for _, other in ipairs(self.Tabs) do
		local active = other == tab
		other._active = active
		other._page.Visible = active
		other._bar.Visible = active
		other._underline.Visible = active
		apply(other._button, not instant, TWEEN_FAST, {
			BackgroundTransparency = active and 0.35 or 1,
			TextColor3 = active and Library.Theme.Text or Library.Theme.SubText,
		})
	end
	if tab and tab._builder then
		tab:_build()
	end
end

